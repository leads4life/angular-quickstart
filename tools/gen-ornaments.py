#!/usr/bin/env python3
"""Generate src/ornaments.css: seam rules, footer pattern and soft photo masks.

Run:  python3 tools/gen-ornaments.py   (writes src/ornaments.css)
All ornaments are SVG data URIs held in CSS variables, so each motif is
defined exactly once and reused everywhere.
"""
import math, pathlib, random, re, urllib.parse

GOLD, GOLD_DK, GOLD_ON_CREAM = "#d2a856", "#7a5320", "#a97f35"


def uri(svg: str) -> str:
    svg = re.sub(r"\s+", " ", svg).strip()
    return 'url("data:image/svg+xml,' + urllib.parse.quote(svg, safe=" =:/,.-") + '")'


# ---- glyphs from the restaurant's world, each in a 9 x 9.6 box -------------
GLYPHS = {
    # auspicious cloud (xiangyun)
    "cloud": '<circle cx="2.7" cy="5.6" r="2.2"/><circle cx="5" cy="4" r="2.8"/>'
             '<circle cx="7.1" cy="6" r="1.9"/><rect x="1.4" y="6.1" width="6.9" height="1.9" rx=".95"/>',
    # round coin with a square hole
    "coin": '<path fill-rule="evenodd" d="M0,4.8a4.5,4.5 0 1,0 9,0a4.5,4.5 0 1,0 -9,0Z M3.2,3.5h2.6v2.6h-2.6Z"/>',
    # paper lantern with cap, base and tassel
    "lantern": '<rect x="3" y=".2" width="3" height="1.2" rx=".3"/><ellipse cx="4.5" cy="4.8" rx="3.9" ry="3.3"/>'
               '<rect x="3" y="8.1" width="3" height="1" rx=".3"/><rect x="4.15" y="9.1" width=".7" height="1.4"/>',
    # lattice knot: a diamond with a diamond hole
    "knot": '<path fill-rule="evenodd" d="M4.5,0 L9,4.8 L4.5,9.6 L0,4.8Z M4.5,2.7 L6.6,4.8 L4.5,6.9 L2.4,4.8Z"/>',
}
ORDER = ("cloud", "coin", "lantern", "coin")


def glyph_rule(color, cell=64, H=16, s=1.0, gap=10, alpha=.6):
    """Fine double rule broken by small glyphs (section-to-section seams)."""
    W = cell * len(ORDER); y1, y2 = H / 2 - 1.6, H / 2 + 1.6; out = []
    for i, k in enumerate(ORDER):
        x0, cx = i * cell, i * cell + cell / 2
        out += [f'<path d="M{x0},{y} H{cx-gap} M{cx+gap},{y} H{x0+cell}" stroke="{color}" stroke-width=".9" opacity="{alpha}"/>' for y in (y1, y2)]
        out.append(f'<g transform="translate({cx-4.5*s:.2f},{H/2-4.8*s:.2f}) scale({s})" fill="{color}" opacity="{min(1, alpha + .3):.2f}">{GLYPHS[k]}</g>')
    svg = f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}" preserveAspectRatio="none">{"".join(out)}</svg>'
    return uri(svg), W, H


def seigaiha(color=GOLD, W=40, H=20, alpha=.11):
    """Overlapping wave scales (the mockups' footer pattern); rows drawn top-down so lower scales overlap."""
    out = []
    for row, y in enumerate((0, 10, 20, 30, 40)):
        xs = (20,) if row % 2 == 0 else (0, 40)
        for x in xs:
            out.append(f'<circle cx="{x}" cy="{y}" r="20" fill="#5a0d12"/>')
            out += [f'<circle cx="{x}" cy="{y}" r="{r}" fill="none" stroke="{color}" stroke-width=".8" opacity="{alpha}"/>' for r in (19.4, 14, 8.6, 3.4)]
    return uri(f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}">{"".join(out)}</svg>')


def blob(seed, n=28, exp=4.6, wobble=.012):
    """Soft squircle with a gentle inward-only wobble in a 0..100 box (stretched to the photo)."""
    rnd = random.Random(seed); pts = []
    for i in range(n):
        t = 2 * math.pi * i / n + rnd.uniform(-.025, .025); c, s = math.cos(t), math.sin(t)
        x, y = math.copysign(abs(c) ** (2 / exp), c), math.copysign(abs(s) ** (2 / exp), s)
        k = 1 - wobble * (.5 + .5 * math.sin(3 * t + seed)) * (.6 + .4 * rnd.random()); pts.append((50 + 49.2 * x * k, 50 + 49.2 * y * k))
    d = f"M{pts[0][0]:.2f},{pts[0][1]:.2f} "
    for i in range(n):  # closed Catmull-Rom -> cubic Bezier
        p0, p1, p2, p3 = pts[i - 1], pts[i], pts[(i + 1) % n], pts[(i + 2) % n]
        d += (f"C{p1[0] + (p2[0] - p0[0]) / 6:.2f},{p1[1] + (p2[1] - p0[1]) / 6:.2f} "
              f"{p2[0] - (p3[0] - p1[0]) / 6:.2f},{p2[1] - (p3[1] - p1[1]) / 6:.2f} {p2[0]:.2f},{p2[1]:.2f} ")
    return uri(f'<svg xmlns="http://www.w3.org/2000/svg" width="100" height="100" viewBox="0 0 100 100" preserveAspectRatio="none"><path d="{d}Z" fill="#000"/></svg>')


rule, rw, rh = glyph_rule(GOLD_ON_CREAM)
rule_dk, _, _ = glyph_rule(GOLD, alpha=.75)
rule_sm, sw, sh = glyph_rule(GOLD_ON_CREAM, cell=56, H=14, s=.85, gap=9, alpha=.45)
rule_ft, _, _ = glyph_rule(GOLD, cell=56, H=14, s=.85, gap=9, alpha=.42)

css = f"""/* GENERATED by tools/gen-ornaments.py. Edit the script, not this file. */
:root {{
  --seigaiha: {seigaiha()};
}}
"""
out = pathlib.Path(__file__).resolve().parent.parent / "src" / "ornaments.css"
out.write_text(css)
print("wrote", out, len(css), "bytes")
